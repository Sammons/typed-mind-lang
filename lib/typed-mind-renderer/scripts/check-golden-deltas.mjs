#!/usr/bin/env node
// RFC-TM-6 §4 (rfc-tm-6-diamond.md) — the executable golden-diff gate. Diffs
// goldens/legacy-baseline/ (pinned permanently after Q1) against the live
// goldens tree and classifies every differing entry into a named cause
// class with an exact-count census. Unclassified deltas or count drift
// exit 1. The classifier compares two checked-in file sets; it never runs
// the legacy engine, so it survives TM-4 Q5's legacy-engine deletion
// unchanged (§4 "No retirement dependency").
//
// Q1 (this Quantum) is additive-only capture — goldens/live/ does not exist
// yet because no flip has happened. In that state the gate is trivially
// green: there is nothing to diff, so every named cause class censuses at
// 0 and the run passes. From Q2 onward, `goldens/live/` is regenerated by
// the flipped renderer/converter and this script's censuses become load-
// bearing (GRAPH-SELF-EXPORT-LINKS=8, A11-ERRORS-VANISH=3, A6-CIRCULAR,
// ERRSHAPE, EMITTER-STRUCTURE, per the doc's §4).

import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const PACKAGE_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const BASELINE_DIR = join(PACKAGE_ROOT, 'goldens', 'legacy-baseline');
const LIVE_DIR = join(PACKAGE_ROOT, 'goldens', 'live');

// Named cause classes and their frozen exact-count censuses (§4). A class
// with `expected: null` has no fixed count yet (A6-CIRCULAR's census is
// "per its frozen census" — TM-4 owns that number; TM-6 records deltas
// under this class without asserting a count until that census is cited
// here by a future Quantum).
const CAUSE_CLASSES = {
  'GRAPH-SELF-EXPORT-LINKS': { expected: 8 },
  'A11-ERRORS-VANISH': { expected: 3 },
  'A6-CIRCULAR': { expected: null },
  ERRSHAPE: { expected: null },
  'EMITTER-STRUCTURE': { expected: null },
};

class GoldenDeltaError extends Error {}

const walkFiles = (dir, out) => {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      walkFiles(full, out);
    } else {
      out.push(full);
    }
  }
};

const main = () => {
  if (!existsSync(BASELINE_DIR)) {
    throw new GoldenDeltaError(
      `${BASELINE_DIR} not found — run the Q1 golden-capture tests first (node --test) to establish the pinned baseline.`,
    );
  }

  if (!existsSync(LIVE_DIR)) {
    console.log(
      '[check-golden-deltas] PASS — goldens/live/ does not exist yet (no flip has landed); nothing to diff. All cause-class censuses at 0.',
    );
    return;
  }

  const baselineFiles = [];
  walkFiles(BASELINE_DIR, baselineFiles);
  const liveFiles = [];
  walkFiles(LIVE_DIR, liveFiles);

  const baselineRel = new Set(baselineFiles.map((f) => relative(BASELINE_DIR, f)));
  const liveRel = new Set(liveFiles.map((f) => relative(LIVE_DIR, f)));

  const missingFromLive = [...baselineRel].filter((f) => !liveRel.has(f));
  const unexpectedInLive = [...liveRel].filter((f) => !baselineRel.has(f));

  const unclassified = [];
  const censusCounts = Object.fromEntries(Object.keys(CAUSE_CLASSES).map((name) => [name, 0]));

  for (const relPath of baselineRel) {
    if (!liveRel.has(relPath)) {
      continue;
    }
    const baselineContent = readFileSync(join(BASELINE_DIR, relPath), 'utf8');
    const liveContent = readFileSync(join(LIVE_DIR, relPath), 'utf8');
    if (baselineContent === liveContent) {
      continue;
    }
    // Q1 ships no classification logic beyond "identical or not" — the
    // per-line/per-entry classifiers named in §4 (GRAPH-SELF-EXPORT-LINKS,
    // A11-ERRORS-VANISH, A6-CIRCULAR, ERRSHAPE, EMITTER-STRUCTURE) are Q2/Q3
    // work: those Quantums own the flip that produces the deltas this
    // script must then classify, and each will extend this file with its
    // classifier function in the same PR that introduces its deltas.
    unclassified.push(relPath);
  }

  if (missingFromLive.length > 0 || unexpectedInLive.length > 0 || unclassified.length > 0) {
    const lines = [];
    if (missingFromLive.length > 0) {
      lines.push(`  missing from goldens/live/: ${missingFromLive.join(', ')}`);
    }
    if (unexpectedInLive.length > 0) {
      lines.push(`  unexpected in goldens/live/ (not in baseline): ${unexpectedInLive.join(', ')}`);
    }
    if (unclassified.length > 0) {
      lines.push(`  unclassified content deltas: ${unclassified.join(', ')}`);
    }
    throw new GoldenDeltaError(`golden delta gate failed:\n${lines.join('\n')}`);
  }

  for (const [name, { expected }] of Object.entries(CAUSE_CLASSES)) {
    if (expected !== null && censusCounts[name] !== expected) {
      throw new GoldenDeltaError(`cause class ${name}: expected exact count ${expected}, got ${censusCounts[name]}`);
    }
  }

  console.log(`[check-golden-deltas] PASS — goldens/live/ matches goldens/legacy-baseline/ (${baselineRel.size} files compared, 0 deltas)`);
};

try {
  main();
} catch (error) {
  if (error instanceof GoldenDeltaError) {
    console.error(`[check-golden-deltas] FAIL: ${error.message}`);
  } else {
    console.error('[check-golden-deltas] FAIL:', error);
  }
  process.exit(1);
}
